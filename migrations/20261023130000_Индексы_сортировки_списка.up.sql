-- Индексы под сортировку списка журнала (тикет #41): сортировка
-- `ORDER BY created_at, id` опирается на индекс вместо полного скана
-- с сортировкой. Тай-брейк по id входит в ключ индекса: TIMESTAMPTZ(0)
-- даёт совпадения внутри секунды, и порядок страницы остаётся
-- детерминированным силами самого индекса в обоих направлениях.
CREATE INDEX changes_created_at_id_index ON public.changes (created_at, id);

-- Вариант с источником первым (ADR-0005): фильтр по источнику —
-- доминирующий сценарий чтения журнала, условие и сортировка
-- обслуживаются одним индексом без сортировки результата.
CREATE INDEX changes_source_created_at_index ON public.changes (source, created_at, id);
